"""One level of an infinite-zoom chain, generated outward with Krea 2 on the render PC's ComfyUI.

The inner image is pasted into a W x H canvas (centred at 1/scale of the frame by default, or at
an explicit `place` rect) and everything around it is generated by masked Krea 2 Turbo img2img
(SetLatentNoiseMask + DifferentialDiffusion with a soft mask), so the new frame wraps a "door"
(screen, window, ...) around the inner image. The zoom compositor later draws the TRUE inner
image back on top with the same feather, so only the ring has to be generated.

params.args = [<job json string>, <out dir>]. Job JSON:
  {"inner": "spikes/infinite_zoom/in/l0.png", "prompt": "...", "seeds": [1, 2, 3],
   "W": 1088, "H": 1920, "scale": 2.5, "place": null, "feather": 0.06,
   "denoise": 1.0, "steps": 8, "lora": null, "lora_strength": 0.8}
`place` = [x, y, w, h] in canvas px overrides `scale` (used to extend a landscape photo to 9:16).
`feather` is a fraction of the inner rect's short side: the mask ramps 0 -> 1 from that far
inside the rect to its edge, so the door's frame can bite slightly into the pasted image.
Writes <out>/s<seed>.png per seed plus <out>/canvas.png and <out>/mask.png.
"""
import json
import os
import shutil
import sys
import time
import uuid

import httpx
import numpy as np

COMFY = os.environ.get("COMFYUI_URL", "http://127.0.0.1:8188").rstrip("/")
T = httpx.Timeout(30.0, read=600.0)
UNET = "krea2_turbo_fp8_scaled.safetensors"
CLIP = "qwen3vl_4b_fp8_scaled.safetensors"
VAE = "qwen_image_vae.safetensors"


def graph(canvas, mask, prompt, seed, steps, denoise, prefix, lora, lora_strength):
    model = ["1", 0]
    g = {
        "1": {"class_type": "UNETLoader", "inputs": {"unet_name": UNET, "weight_dtype": "default"}},
        "2": {"class_type": "CLIPLoader", "inputs": {"clip_name": CLIP, "type": "krea2"}},
        "3": {"class_type": "VAELoader", "inputs": {"vae_name": VAE}},
        "4": {"class_type": "CLIPTextEncode", "inputs": {"text": prompt, "clip": ["2", 0]}},
        "5": {"class_type": "ConditioningZeroOut", "inputs": {"conditioning": ["4", 0]}},
        "6": {"class_type": "LoadImage", "inputs": {"image": canvas}},
        "7": {"class_type": "VAEEncode", "inputs": {"pixels": ["6", 0], "vae": ["3", 0]}},
        "11": {"class_type": "LoadImageMask", "inputs": {"image": mask, "channel": "red"}},
        "12": {"class_type": "SetLatentNoiseMask", "inputs": {"samples": ["7", 0], "mask": ["11", 0]}},
    }
    if lora:
        g["14"] = {"class_type": "LoraLoaderModelOnly",
                   "inputs": {"model": model, "lora_name": lora, "strength_model": float(lora_strength)}}
        model = ["14", 0]
    g["13"] = {"class_type": "DifferentialDiffusion", "inputs": {"model": model}}
    g["8"] = {"class_type": "KSampler",
              "inputs": {"model": ["13", 0], "seed": int(seed), "steps": int(steps), "cfg": 1.0,
                         "sampler_name": "euler", "scheduler": "simple", "positive": ["4", 0],
                         "negative": ["5", 0], "latent_image": ["12", 0], "denoise": float(denoise)}}
    g["9"] = {"class_type": "VAEDecode", "inputs": {"samples": ["8", 0], "vae": ["3", 0]}}
    g["10"] = {"class_type": "SaveImage", "inputs": {"images": ["9", 0], "filename_prefix": prefix}}
    return g


def upload(path):
    with open(path, "rb") as f:
        r = httpx.post(COMFY + "/upload/image", files={"image": (os.path.basename(path), f)},
                       data={"subfolder": "izoom", "type": "input", "overwrite": "true"}, timeout=T)
    r.raise_for_status()
    j = r.json()
    return f"{j['subfolder']}/{j['name']}" if j.get("subfolder") else j["name"]


def run_png(g, dest, timeout_s=1800):
    r = httpx.post(COMFY + "/prompt", json={"prompt": g, "client_id": str(uuid.uuid4())}, timeout=T)
    if r.status_code != 200:
        raise RuntimeError(f"/prompt rejected {r.status_code}: {r.text[:2000]}")
    pid = r.json()["prompt_id"]
    t0 = time.monotonic()
    while time.monotonic() - t0 < timeout_s:
        try:
            e = httpx.get(COMFY + f"/history/{pid}", timeout=60).json().get(pid)
        except httpx.TimeoutException:
            continue
        if e:
            st = e.get("status") or {}
            if st.get("status_str") == "error":
                msgs = st.get("messages") or []
                err = next((m[1] for m in msgs if m[0] == "execution_error"), {})
                raise RuntimeError(f"execution error at {err.get('node_type')}: {err.get('exception_message')}")
            for node_out in (e.get("outputs") or {}).values():
                for f in node_out.get("images", []) or []:
                    if f.get("type", "output") == "output":
                        params = {"filename": f["filename"], "subfolder": f.get("subfolder", ""), "type": "output"}
                        with httpx.stream("GET", COMFY + "/view", params=params, timeout=T) as resp:
                            resp.raise_for_status()
                            with open(dest, "wb") as out:
                                for chunk in resp.iter_bytes(1 << 20):
                                    out.write(chunk)
                        return time.monotonic() - t0
            raise RuntimeError("no image in outputs")
        time.sleep(2)
    raise RuntimeError("timed out")


def clear_out(out):
    """The output dir sits in a reused repo cache and is zipped whole: start it empty."""
    os.makedirs(out, exist_ok=True)
    for name in os.listdir(out):
        q = os.path.join(out, name)
        shutil.rmtree(q, ignore_errors=True) if os.path.isdir(q) else os.remove(q)


def build_canvas(inner, W, H, place, feather):
    """Canvas = blurred stretch of the inner image with the sharp inner pasted at `place`;
    mask = 1 outside, 0 well inside, linear ramp over the feather band just inside the rect."""
    import cv2
    x, y, w, h = place
    bg = cv2.GaussianBlur(cv2.resize(inner, (W, H), interpolation=cv2.INTER_AREA), (0, 0), 25)
    canvas = bg.copy()
    canvas[y:y + h, x:x + w] = cv2.resize(inner, (w, h), interpolation=cv2.INTER_AREA)
    band = max(2.0, feather * min(w, h))
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    # distance inside the rect to its nearest edge (negative outside)
    d = np.minimum(np.minimum(xx - x, x + w - 1 - xx), np.minimum(yy - y, y + h - 1 - yy))
    mask = np.clip(1.0 - d / band, 0.0, 1.0)
    return canvas, (mask * 255).astype(np.uint8)


def main():
    import cv2
    job = json.loads(sys.argv[1])
    out = os.path.abspath(sys.argv[2])
    clear_out(out)
    W, H = int(job.get("W", 1088)), int(job.get("H", 1920))
    inner = cv2.imread(job["inner"], cv2.IMREAD_COLOR)
    if inner is None:
        raise RuntimeError(f"cannot read {job['inner']}")
    if job.get("place"):
        place = [int(v) for v in job["place"]]
    else:
        s = float(job.get("scale", 2.5))
        w, h = int(round(W / s)), int(round(H / s))
        place = [(W - w) // 2, (H - h) // 2, w, h]
    canvas, mask = build_canvas(inner, W, H, place, float(job.get("feather", 0.06)))
    cp, mp = os.path.join(out, "canvas.png"), os.path.join(out, "mask.png")
    cv2.imwrite(cp, canvas)
    cv2.imwrite(mp, mask)
    with open(os.path.join(out, "place.json"), "w") as f:
        json.dump({"W": W, "H": H, "place": place, "feather": job.get("feather", 0.06)}, f)
    c_ref, m_ref = upload(cp), upload(mp)
    seeds = job.get("seeds", [1, 2, 3])
    try:
        for i, seed in enumerate(seeds):
            g = graph(c_ref, m_ref, job["prompt"], seed, job.get("steps", 8), job.get("denoise", 1.0),
                      "izoom/lvl", job.get("lora"), job.get("lora_strength", 0.8))
            secs = run_png(g, os.path.join(out, f"s{seed}.png"))
            print(f"seed {seed}: {secs:.0f}s", flush=True)
            print(f"PROGRESS {int((i + 1) * 100 / len(seeds))}", flush=True)
    finally:
        httpx.post(COMFY + "/free", json={"unload_models": True, "free_memory": True}, timeout=60)


if __name__ == "__main__":
    main()
